pub struct CharacterRom;

impl CharacterRom {
    pub fn new() -> Self {
        Self
    }

    pub fn read_row(&self, ascii_code: u8, row: u8) -> u8 {
        if ascii_code > 127 || row > 7 {
            return 0;
        }
        let index = (ascii_code as usize * 8) + row as usize;
        FONT_8X8_DATA[index]
    }
}

